function координаты(событие) {
  const svg = $("оверлей");
  const рамка = svg.getBoundingClientRect();
  const к = состояние.текущий.canvas / рамка.width;
  return [(событие.clientX - рамка.left) * к, (событие.clientY - рамка.top) * к];
}

function фигура(ключ) {
  return состояние.фигуры.find((ф) => ф.key === ключ);
}

/* Правка копится по полям: тронули конец габарита — записан только конец, всё
   остальное по-прежнему считает раскладка. Так одна правка не замораживает
   кадр целиком и не мешает автомату поумнеть в остальном. */
function правка(ключ) {
  if (!состояние.правки[ключ]) состояние.правки[ключ] = {};
  состояние.правлено = true;
  return состояние.правки[ключ];
}

function развернуть(ключ) {
  const ф = фигура(ключ);
  if (!ф || ф.kind !== "leader") return;
  ф.direction = -ф.direction;
  правка(ключ).direction = ф.direction;
  нарисовать_оверлей();
  сохранить(состояние.текущий.item.id, "Полка развёрнута в другую сторону");
}

document.addEventListener("pointerdown", (событие) => {
  const цель = событие.target;
  if (!цель.closest || !цель.closest("#оверлей")) return;
  const угол = цель.dataset?.угол;
  const роль = цель.dataset?.роль;
  const ключ = цель.dataset?.ключ;
  if (угол === undefined && !роль) return;

  событие.preventDefault();
  if (роль === "разворот") { развернуть(ключ); return; }

  цель.setPointerCapture?.(событие.pointerId);
  document.body.classList.add("тянем");
  const старт = координаты(событие);
  const начальная = { ...состояние.рамка };
  const ф = ключ ? фигура(ключ) : null;
  const было = ф ? JSON.parse(JSON.stringify(ф)) : null;

  const тянуть = (e) => {
    const [x, y] = координаты(e);
    if (ф && роль === "конец") {
      const значение = ф.axis === "h" ? x : y;
      ф[цель.dataset.конец] = значение;
      правка(ключ)[цель.dataset.конец] = значение;
    } else if (ф && роль === "конец-точка") {
      const [nx, ny] = ф.normal;
      const т = [x - nx * ф.offset, y - ny * ф.offset];
      ф[цель.dataset.конец] = т;
      правка(ключ)[цель.dataset.конец] = т;
    } else if (ф && роль === "уровень") {
      ф.level = ф.axis === "h" ? y : x;
      // сторона решает, куда пойдут выносные: перетащенная через изделие линия
      // иначе стреляла бы ими в противоположную сторону
      const середина = ф.box
        ? (ф.axis === "h" ? (ф.box[1] + ф.box[3]) / 2 : (ф.box[0] + ф.box[2]) / 2)
        : ф.level;
      ф.side = ф.level < середина ? -1 : 1;
      правка(ключ).level = ф.level;
    } else if (ф && роль === "смещение") {
      const [nx, ny] = ф.normal;
      const середина = [(ф.a[0] + ф.b[0]) / 2, (ф.a[1] + ф.b[1]) / 2];
      ф.offset = (x - середина[0]) * nx + (y - середина[1]) * ny;
      правка(ключ).offset = ф.offset;
    } else if (ф && роль === "якорь") {
      ф.anchor = [x, y];
      правка(ключ).anchor = ф.anchor;
    } else if (ф && роль === "полка") {
      ф.elbow = [x, y];
      правка(ключ).elbow = ф.elbow;
    } else if (ф && роль === "интервал") {
      ф.span[Number(цель.dataset.конец)] = [x, y];
      правка(ключ).span = ф.span;
    } else if (роль === "шинка" && состояние.шинка) {
      состояние.шинка = [x, y];
      состояние.правлено = true;
    } else if (роль === "поворот") {
      const угол_рад = Math.atan2(y - начальная.cy, x - начальная.cx);
      let градусы = (угол_рад * 180) / Math.PI + 90;
      while (градусы > 90) градусы -= 180;
      while (градусы <= -90) градусы += 180;
      состояние.рамка.angle = e.shiftKey ? Math.round(градусы / 15) * 15 : градусы;
      состояние.правлено = true;
    } else if (угол !== undefined) {
      const i = Number(угол);
      const противоположный = углы(начальная)[(i + 2) % 4];
      const a = (начальная.angle * Math.PI) / 180;
      const u = [Math.cos(a), Math.sin(a)];
      const n = [-u[1], u[0]];
      const dx = x - противоположный[0], dy = y - противоположный[1];
      const du = dx * u[0] + dy * u[1];
      const dn = dx * n[0] + dy * n[1];
      состояние.рамка.long = Math.max(12, Math.abs(du));
      состояние.рамка.short = Math.max(12, Math.abs(dn));
      состояние.рамка.cx = противоположный[0] + dx / 2;
      состояние.рамка.cy = противоположный[1] + dy / 2;
      состояние.правлено = true;
    } else if (роль === "тело") {
      состояние.рамка.cx = начальная.cx + (x - старт[0]);
      состояние.рамка.cy = начальная.cy + (y - старт[1]);
      состояние.правлено = true;
    }
    нарисовать_оверлей();
  };

  const бросить = () => {
    document.removeEventListener("pointermove", тянуть);
    document.removeEventListener("pointerup", бросить);
    document.body.classList.remove("тянем");
    // список размеров показывает, что правлено, — после броска он устарел
    if (ф && было && JSON.stringify(ф) !== JSON.stringify(было)) обновить_список_размеров();
  };
  document.addEventListener("pointermove", тянуть);
  document.addEventListener("pointerup", бросить);
});

function обновить_список_размеров() {
  const список = $("деталь")?.querySelector(".размеры");
  if (!список) return;
  const свежий = document.createElement("div");
  свежий.innerHTML = блок_линий();
  список.replaceWith(свежий.querySelector(".размеры"));
  подключить_список_размеров();
}

