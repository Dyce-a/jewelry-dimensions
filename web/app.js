/* Стартовое значение data-тема ставит короткий скрипт в <head>, иначе страница
   мигает светлым. Здесь только переключение и подпись на кнопке. */

const ИМЯ_ТЕМЫ = { "светлая": "Светлая", "тёмная": "Тёмная" };

function текущая_тема() {
  return document.documentElement.getAttribute("data-тема") === "тёмная"
    ? "тёмная" : "светлая";
}

function применить_тему(имя, запомнить = true) {
  document.documentElement.setAttribute("data-тема", имя);
  if (запомнить) {
    try { localStorage.setItem("тема", имя); } catch (e) {}
  }
  const подпись = $("тема-подпись");
  if (подпись) подпись.textContent = ИМЯ_ТЕМЫ[имя] || "Тема";
  $("тема").title = имя === "тёмная"
    ? "Сейчас тёмная — включить светлую"
    : "Сейчас светлая — включить тёмную";
}

$("тема").onclick = () => {
  применить_тему(текущая_тема() === "тёмная" ? "светлая" : "тёмная");
};

