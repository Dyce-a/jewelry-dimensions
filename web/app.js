async function принять_картинки(файлы) {
  for (const файл of файлы) {
    if (!файл.type.startsWith("image/")) continue;
    const данные = await новый_размер(файл, 1400);
    состояние.вложения.push({ имя: файл.name || "картинка", данные });
  }
  показать_вложения();
}

function новый_размер(файл, сторона) {
  // ужимаем прямо в браузере: гнать через сеть двадцать мегапикселей незачем
  return new Promise((готово, беда) => {
    const чтец = new FileReader();
    чтец.onerror = беда;
    чтец.onload = () => {
      const кадр = new Image();
      кадр.onerror = беда;
      кадр.onload = () => {
        const к = Math.min(1, сторона / Math.max(кадр.width, кадр.height));
        const холст = document.createElement("canvas");
        холст.width = Math.round(кадр.width * к);
        холст.height = Math.round(кадр.height * к);
        холст.getContext("2d").drawImage(кадр, 0, 0, холст.width, холст.height);
        готово(холст.toDataURL("image/jpeg", 0.88));
      };
      кадр.src = чтец.result;
    };
    чтец.readAsDataURL(файл);
  });
}

