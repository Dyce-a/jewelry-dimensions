// ---------------------------------------------------------------- геометрия разметки

/* Схема в редакторе и анимация нанесения рисуют те же линии, что легли в PNG,
   поэтому геометрия описана здесь один раз: `части_фигуры` переводит фигуру
   разметки в набор примитивов, а рисуют их два разных обработчика — оверлей с
   ручками и чертёж, который проявляется по очереди. Мерки стиля (кегль подписи,
   вынос засечки, длина полки) приходят с сервера вместе с разбором: считать их
   заново в браузере значит развести схему с кадром. */

const мерка = document.createElement("canvas").getContext("2d");

function ширина_текста(текст, размер, жирность = 600) {
  мерка.font = `${жирность} ${размер}px Montserrat, "Segoe UI", sans-serif`;
  return мерка.measureText(текст).width;
}

function стиль_кадра() {
  return состояние.текущий?.style || {
    label: 67, caption: 30, line: 3, offset: 122, leader: 266,
    tick: 41, ext: 188, gap: 22, break: 34, band_tick: 20, dot: 6,
  };
}

const вдоль = (ось, в, поперёк) => (ось === "h" ? [в, поперёк] : [поперёк, в]);
const линия = (a, b) => ({ вид: "линия", x1: a[0], y1: a[1], x2: b[0], y2: b[1] });
const точка = (т, r) => ({ вид: "точка", x: т[0], y: т[1], r });
const текст = (т, строка, размер, поворот = 0, род = "число") =>
  ({ вид: "текст", x: т[0], y: т[1], текст: строка, размер, поворот, род });

/* Угол подписи вдоль направления, головой вверх. В отрисовке кадра поворот
   считается против часовой стрелки, в SVG — по часовой, поэтому знак обратный. */
function поворот_вдоль(ux, uy) {
  let градусы = (Math.atan2(uy, ux) * 180) / Math.PI;
  while (градусы <= -90) градусы += 180;
  while (градусы > 90) градусы -= 180;
  return градусы;
}

function стрелка(конец, направление, размер) {
  const [dx, dy] = направление;
  const норма = Math.hypot(dx, dy) || 1;
  const [ux, uy] = [dx / норма, dy / норма];
  const [px, py] = [-uy, ux];
  const зад = [конец[0] - ux * размер, конец[1] - uy * размер];
  const точки = [конец,
    [зад[0] + px * размер * 0.45, зад[1] + py * размер * 0.45],
    [зад[0] - px * размер * 0.45, зад[1] - py * размер * 0.45]];
  return { вид: "многоугольник", точки: точки.map((т) => т.join(",")).join(" ") };
}

/* Докуда идёт выносная линия габарита. Кромку под концом на кадре ищет луч по
   маске; в браузере маски нет, поэтому берётся кромка рамки элемента с тем же
   ограничением по длине, что и в отрисовке: далеко отстоящая кромка заменяется
   короткой засечкой. */
function край_выносной(ф, сторона, с) {
  const за = ф.level + с.tick * сторона;
  let край = ф.base;
  if (ф.box) {
    край = ф.axis === "h"
      ? (сторона < 0 ? ф.box[1] : ф.box[3])
      : (сторона < 0 ? ф.box[0] : ф.box[2]);
  }
  край += с.gap * сторона;
  const ход = (за - край) * сторона;
  if (ход < с.tick) return за - с.tick * сторона;
  if (ход > с.ext * 4) return за - с.ext * сторона;
  return край;
}

/* Конец полки выноски. Полка укорачивается, а при нехватке места разворачивается
   в другую сторону — иначе число уезжает за холст. Правило то же, что в отрисовке
   (`Renderer._fit_shelf`): схема обязана показывать линию там, где она встанет. */
function полка_выноски(ф, с) {
  const край = с.canvas || 2000;
  const нужно = с.break + ширина_текста(ф.text, с.label) + (с.pad || 4) * 2 + с.margin;
  for (const знак of [ф.direction, -ф.direction]) {
    const предел = знак > 0 ? край - нужно : нужно;
    let далеко = ф.elbow[0] + знак * ф.length;
    далеко = знак > 0 ? Math.min(далеко, предел) : Math.max(далеко, предел);
    if ((далеко - ф.elbow[0]) * знак >= с.tick) {
      return { конец: [далеко, ф.elbow[1]], сторона: знак };
    }
  }
  return { конец: [ф.elbow[0] + ф.direction * с.tick, ф.elbow[1]], сторона: ф.direction };
}

function части_фигуры(ф) {
  const с = стиль_кадра();
  const части = [];
  if (ф.kind === "linear") {
    const a = Math.min(ф.a, ф.b), b = Math.max(ф.a, ф.b);
    const сторона = ф.side || -1;
    const за = ф.level + с.tick * сторона;
    const край = край_выносной(ф, сторона, с);
    for (const з of [a, b]) части.push(линия(вдоль(ф.axis, з, край), вдоль(ф.axis, з, за)));
    const ш = ширина_текста(ф.text, с.label);
    if (b - a >= ш + 2 * с.break + 2 * с.tick) {
      const середина = (a + b) / 2, половина = ш / 2 + с.break;
      части.push(линия(вдоль(ф.axis, a, ф.level), вдоль(ф.axis, середина - половина, ф.level)));
      части.push(линия(вдоль(ф.axis, середина + половина, ф.level), вдоль(ф.axis, b, ф.level)));
      части.push(текст(вдоль(ф.axis, середина, ф.level), ф.text, с.label,
                       ф.axis === "v" ? -90 : 0));
    } else {
      части.push(линия(вдоль(ф.axis, a, ф.level), вдоль(ф.axis, b, ф.level)));
      const отступ = с.break + с.dot;
      if (ф.axis === "h") {
        const хвост = с.break * 1.6;
        части.push(линия([b, ф.level], [b + хвост, ф.level]));
        части.push(текст([b + хвост + отступ + ш / 2, ф.level], ф.text, с.label));
      } else {
        части.push(текст([ф.level + (сторона || 1) * (отступ + ш / 2), (a + b) / 2],
                         ф.text, с.label));
      }
    }
    for (const з of [a, b]) части.push(точка(вдоль(ф.axis, з, ф.level), с.dot));
  } else if (ф.kind === "inclined") {
    const [nx, ny] = ф.normal;
    const сдвиг = (т, d) => [т[0] + nx * d, т[1] + ny * d];
    const начало = сдвиг(ф.a, ф.offset), конец = сдвиг(ф.b, ф.offset);
    const длина = Math.hypot(конец[0] - начало[0], конец[1] - начало[1]) || 1;
    const [ux, uy] = [(конец[0] - начало[0]) / длина, (конец[1] - начало[1]) / длина];
    for (const т of [ф.a, ф.b]) части.push(линия(сдвиг(т, с.gap), сдвиг(т, ф.offset + с.tick)));
    const ш = ширина_текста(ф.text, с.label);
    const середина = [(начало[0] + конец[0]) / 2, (начало[1] + конец[1]) / 2];
    if (длина >= ш + 2 * с.break + 2 * с.tick) {
      const половина = ш / 2 + с.break;
      части.push(линия(начало, [середина[0] - ux * половина, середина[1] - uy * половина]));
      части.push(линия([середина[0] + ux * половина, середина[1] + uy * половина], конец));
      части.push(текст(середина, ф.text, с.label, поворот_вдоль(ux, uy)));
    } else {
      части.push(линия(начало, конец));
      const хвост = с.break * 1.6;
      const кончик = [конец[0] + ux * хвост, конец[1] + uy * хвост];
      части.push(линия(конец, кончик));
      const отступ = с.break + с.dot + ш / 2;
      части.push(текст([кончик[0] + ux * отступ, кончик[1] + uy * отступ], ф.text, с.label));
    }
    for (const т of [начало, конец]) части.push(точка(т, с.dot));
  } else if (ф.kind === "leader") {
    const { конец: полка, сторона } = полка_выноски(ф, с);
    if (ф.span) {
      const [[x0, y0], [x1, y1]] = ф.span;
      const длина = Math.hypot(x1 - x0, y1 - y0) || 1;
      const [px, py] = [-(y1 - y0) / длина, (x1 - x0) / длина];
      части.push({ ...линия(ф.span[0], ф.span[1]), род: "интервал" });
      for (const [x, y] of ф.span) {
        части.push({
          ...линия([x - px * с.band_tick, y - py * с.band_tick],
                   [x + px * с.band_tick, y + py * с.band_tick]),
          род: "интервал",
        });
      }
    } else if (ф.arrow === "v") {
      части.push(стрелка(ф.anchor, [0, ф.anchor[1] <= ф.elbow[1] ? -1 : 1], с.dot * 2.6));
    } else if (ф.arrow === "h") {
      части.push(стрелка(ф.anchor, [-ф.direction, 0], с.dot * 2.6));
    }
    части.push(линия(ф.anchor, ф.elbow));
    части.push(линия(ф.elbow, полка));
    части.push(точка(полка, с.dot));
    const ш = ширина_текста(ф.text, с.label);
    части.push(текст([полка[0] + сторона * (с.break + ш / 2), ф.elbow[1]],
                     ф.text, с.label));
    if (ф.label) {
      const половина = ширина_текста(ф.label, с.caption, 500) / 2 + (с.pad || 4);
      const вверх = ф.anchor[1] > ф.elbow[1];
      const край = с.canvas || 2000;
      const x = Math.min(Math.max(ф.elbow[0] + сторона * (половина + с.break * 0.5),
                                  половина + с.margin), край - половина - с.margin);
      части.push(текст([x, ф.elbow[1] + (вверх ? -с.caption * 2.1 : с.caption * 1.6)],
                       ф.label, с.caption, 0, "подпись"));
    }
  }
  return части;
}

