async function отправить_в_чат(текст, картинки = []) {
  const ключ = состояние.ключ_чата;
  const про_сайт = ключ === "сайт";
  const id = про_сайт ? null : ключ;
  const текущий = чат(ключ);

  текущий.реплики.push({ роль: "человек", текст, картинки });
  текущий.реплики.push({ роль: "опус", текст: "думает…" });
  показать_беседу();
  try {
    const ответ = await запрос("/api/chat", {
      история: текущий.история, id, усилие: состояние.усилие });
    текущий.реплики.pop();
    if (ответ.журнал?.length) {
      текущий.реплики.push({
        роль: "инструменты",
        текст: ответ.журнал.map((з) => `${з.инструмент} — ${з.итог}`).join(" · "),
      });
    }
    текущий.реплики.push({ роль: "опус", текст: ответ.ответ || ответ.ошибка || "—" });
    текущий.история = ответ.история || [];
    показать_беседу();

    // если кадр меняли, перечитываем разбор — но только когда он открыт
    const менявшие = ["подвинул рамку", "переставил якорь высоты", "переставил размер",
                      "вернул размер автомату", "перерисовал", "вернул автоматику",
                      "перенёс правку"];
    const менял = ответ.журнал?.some(
      (з) => з.итог === "выполнено" && менявшие.includes(з.инструмент));
    /* Опус мог тронуть не только открытый кадр: «перенёс правку» задевает соседей,
       а какие именно — из журнала не видно. Тогда освежаем весь показанный набор. */
    if (менял && !про_сайт) {
      const перенос = ответ.журнал.some(
        (з) => з.итог === "выполнено" && з.инструмент === "перенёс правку");
      освежить(перенос ? состояние.позиции.map((п) => п.id) : id);
    }
    if (менял && !про_сайт && состояние.текущий?.item.id === id) {
      const свежий = await запрос(`/api/item/${id}`);
      const было = состояние.вкладка;
      показать(свежий);
      выбрать_вкладку(было);
    } else if (менял && про_сайт) {
      сообщить("Опус правил сайт — обновите страницу, чтобы увидеть", 5200);
    }
  } catch (ошибка) {
    текущий.реплики.pop();
    текущий.реплики.push({ роль: "опус", текст: `Не вышло: ${ошибка.message}` });
    показать_беседу();
  }
}

function подключить_чат() {
  const форма = $("форма-чата");
  if (!форма) return;

  форма.onsubmit = (событие) => {
    событие.preventDefault();
    const поле = $("ввод-чата");
    const текст = поле.value.trim();
    const картинки = состояние.вложения.map((в) => в.данные);
    if (!текст && !картинки.length) return;
    поле.value = "";
    состояние.вложения = [];
    показать_вложения();

    const части = картинки.map((и) => ({
      type: "image",
      source: { type: "base64", media_type: "image/jpeg", data: и.split(",")[1] },
    }));
    части.push({ type: "text", text: текст || "Посмотри на картинку." });
    чат().история = [...чат().история, { role: "user", content: части }];
    отправить_в_чат(текст, картинки);
  };

  $("файлы-чата").onchange = (событие) => {
    принять_картинки(событие.target.files);
    событие.target.value = "";
  };

  $("вложения").onclick = (событие) => {
    const кнопка = событие.target.closest("[data-снять]");
    if (!кнопка) return;
    состояние.вложения.splice(Number(кнопка.dataset.снять), 1);
    показать_вложения();
  };

  for (const кнопка of $("усилия").querySelectorAll(".усилие")) {
    кнопка.onclick = () => {
      состояние.усилие = кнопка.dataset.усилие;
      localStorage.setItem("усилие", состояние.усилие);
      for (const другая of $("усилия").querySelectorAll(".усилие")) {
        другая.toggleAttribute("aria-pressed", другая === кнопка);
      }
    };
  }

  // картинку можно просто бросить на панель чата или вставить из буфера
  const зона = форма.closest(".содержимое");
  for (const имя of ["dragenter", "dragover"]) {
    зона.addEventListener(имя, (e) => {
      e.preventDefault();
      зона.classList.add("ждёт-файл");
    });
  }
  for (const имя of ["dragleave", "drop"]) {
    зона.addEventListener(имя, (e) => {
      e.preventDefault();
      зона.classList.remove("ждёт-файл");
    });
  }
  зона.addEventListener("drop", (e) => принять_картинки(e.dataTransfer.files));
  $("ввод-чата").addEventListener("paste", (e) => {
    const файлы = [...(e.clipboardData?.files || [])];
    if (файлы.length) {
      e.preventDefault();
      принять_картинки(файлы);
    }
  });
}

