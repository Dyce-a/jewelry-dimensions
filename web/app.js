/* Список того, что нарисовано на кадре. Он и оглавление, и пульт: наведение
   подсвечивает линию на снимке, кнопки разворачивают полку и возвращают один
   размер автомату, не трогая остальные правки. */

function блок_линий() {
  const привычки = состояние.текущий.habits || {};
  const строки = состояние.фигуры.map((ф) => {
    const правлен = !!состояние.правки[ф.key];
    const способ = ф.kind === "leader" ? (ф.span ? "интервал" : "выноска") : "габарит";
    return `<li class="размер" data-ключ="${ф.key}">
      <span class="имя">${ф.caption || ф.key}</span>
      <span class="как">${способ} · ${ф.text}</span>
      ${правлен ? `<span class="метка правка">правлено</span>` : ""}
      ${!правлен && привычки[ф.key] ? `<span class="метка привычка">привычка</span>` : ""}
      ${ф.kind === "leader"
        ? `<button class="кнопка тихая" data-развернуть="${ф.key}"
             title="Развернуть полку в другую сторону">${иконка("копия", 12)}</button>`
        : ""}
      <button class="кнопка тихая" data-вернуть="${ф.key}"${правлен ? "" : " disabled"}
        title="Вернуть этот размер автомату">${иконка("обновить", 12)}</button>
    </li>`;
  }).join("");
  return `<section class="блок">
    <h3>${иконка("перо", 13)} Размеры на кадре</h3>
    <div class="содержимое">
      <ul class="размеры">${строки}</ul>
      <p class="мелко">Тяните на кадре: кружок на конце габарита двигает его конец,
        линия целиком — отодвигает размерную линию от изделия, ромб на изломе
        переставляет полку выноски, стрелка показывает, куда указывать. Квадрат на
        конце полки разворачивает её в другую сторону.</p>
      <div class="ряд" style="margin-top:9px">
        <button class="кнопка тихая" id="показать-нанесение">${иконка("перо")} Показать нанесение</button>
      </div>
    </div></section>`;
}

function подключить_список_размеров() {
  for (const строка of $("деталь").querySelectorAll(".размер")) {
    строка.onmouseenter = () => { состояние.подсветка = строка.dataset.ключ; нарисовать_оверлей(); };
    строка.onmouseleave = () => { состояние.подсветка = ""; нарисовать_оверлей(); };
  }
  const id = состояние.текущий.item.id;
  for (const кнопка of $("деталь").querySelectorAll("[data-вернуть]")) {
    кнопка.onclick = () => {
      delete состояние.правки[кнопка.dataset.вернуть];
      сохранить(id, `Размер «${кнопка.dataset.вернуть}» вернулся к автомату`);
    };
  }
  for (const кнопка of $("деталь").querySelectorAll("[data-развернуть]")) {
    кнопка.onclick = () => развернуть(кнопка.dataset.развернуть);
  }
  const показ = $("показать-нанесение");
  if (показ) показ.onclick = () => анимировать_нанесение();
}

