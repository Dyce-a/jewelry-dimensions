function блок_разбора(данные) {
  const s = данные.scale, b = данные.band;
  const расхождение = (Math.exp(s.mismatch) - 1) * 100;
  const промер = b.expected_px > 0 ? Math.abs(b.measured_px - b.expected_px) / b.expected_px * 100 : 0;
  const план = данные.plan;
  return `<section class="блок">
    <h3>${иконка("таблица", 13)} Что посчитал скрипт</h3>
    <div class="содержимое"><dl class="свойства">
      <dt>Тип изделия</dt><dd>${план.item_type}</dd>
      <dt>Ракурс</dt><dd>${план.view}</dd>
      <dt>План</dt><dd>${план.source}${план.manual ? " · правлен" : ""}</dd>
      <dt>Рамка</dt><dd>${данные.decor.source}${данные.decor.inclined ? " · наклонная" : ""}</dd>
      <dt>Оси кадра</dt><dd>${план.axes.horizontal} / ${план.axes.vertical}</dd>
      <dt>На выноске</dt><dd>${план.leader_dim}</dd>
      <dt>Якорь выноски</dt><dd>${данные.leader?.source || "—"}</dd>
      <dt>Масштаб</dt><dd>${s.mm_per_px ? (1 / s.mm_per_px).toFixed(1) + " px/мм" : "—"}</dd>
      <dt>Расхождение осей</dt>
      <dd class="${расхождение > 18 ? "внимание" : "норма"}">${округлить(расхождение, 1)} %</dd>
      <dt>Шинка: промер</dt><dd>${округлить(b.measured_px)} px</dd>
      <dt>Шинка: по таблице</dt>
      <dd class="${промер > 60 ? "внимание" : "норма"}">${округлить(b.expected_px)} px</dd>
      <dt>Ширина шинки видна</dt><dd>${b.visible ? "да" : "нет"}</dd>
    </dl></div></section>`;
}

