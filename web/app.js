/* Разметку показываем чертежом: линии проявляются по очереди, как будто их ведут
   рукой, и только потом на место встаёт готовый PNG. Это не украшение — по
   очереди видно, что откуда взялось: сначала габариты декоративного элемента,
   потом выноска невидимого на ракурсе размера, потом метки шинки. Рисуется тем
   же расчётом, что и сам кадр (`части_фигуры`), поэтому чертёж и результат
   совпадают, а не изображают друг друга. */

const ШАГ_ЛИНИИ = 240;        // сколько чертится одна линия, мс
const ШАГ_ПОДПИСИ = 200;      // сколько проявляется подпись, мс

const пауза = (мс) => new Promise((готово) => setTimeout(готово, мс));

async function анимировать_нанесение() {
  const данные = состояние.текущий;
  if (!данные || !состояние.фигуры.length) return;
  выбрать_вкладку("схема");
  const svg = $("оверлей");
  svg.innerHTML = "";
  svg.classList.add("нанесение");
  const мой = (состояние.чертёж = (состояние.чертёж || 0) + 1);
  const масштаб = данные.canvas / ($("обёртка").clientWidth || данные.canvas);
  const толщина = 2 * масштаб;

  let задержка = 0;
  for (const ф of состояние.фигуры) {
    for (const часть of части_фигуры(ф)) {
      const э = узел_части(часть, "чертёж", толщина);
      svg.append(э);
      // движение задано ключевыми кадрами, а не переходом по requestAnimationFrame:
      // переход требует, чтобы страница успела нарисовать исходное состояние, и на
      // невидимой вкладке линия так и осталась бы несведённой
      э.style.setProperty("--задержка", `${Math.round(задержка)}ms`);
      if (часть.вид === "линия") {
        const длина = Math.hypot(часть.x2 - часть.x1, часть.y2 - часть.y1) || 1;
        э.style.strokeDasharray = длина;
        э.style.setProperty("--ход", длина);
        э.style.setProperty("--длительность", `${ШАГ_ЛИНИИ}ms`);
        э.classList.add("чертится");
        задержка += ШАГ_ЛИНИИ * 0.55;
      } else {
        э.style.setProperty("--длительность", `${ШАГ_ПОДПИСИ}ms`);
        э.classList.add("проявляется");
        задержка += ШАГ_ПОДПИСИ * 0.6;
      }
    }
    задержка += 170;      // пауза между размерами: видно, что размер отдельный
  }

  const пропустить = () => { состояние.чертёж += 1; завершить_нанесение(); };
  $("обёртка").addEventListener("click", пропустить, { once: true });
  сообщить("Наношу разметку — щёлкните по кадру, чтобы не ждать", задержка + 900);
  await пауза(задержка + 400);
  $("обёртка")?.removeEventListener("click", пропустить);
  if (состояние.чертёж === мой) завершить_нанесение();
}

function завершить_нанесение() {
  const svg = $("оверлей");
  if (!svg) return;
  svg.classList.remove("нанесение");
  if (состояние.текущий?.item.ready) выбрать_вкладку("итог");
  else нарисовать_оверлей();
}

