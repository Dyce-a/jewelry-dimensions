function углы(р) {
  const a = (р.angle * Math.PI) / 180;
  const u = [Math.cos(a), Math.sin(a)];
  const n = [-u[1], u[0]];
  const L = р.long / 2, S = р.short / 2;
  return [[-1, -1], [1, -1], [1, 1], [-1, 1]].map(([sx, sy]) => [
    р.cx + sx * u[0] * L + sy * n[0] * S,
    р.cy + sx * u[1] * L + sy * n[1] * S,
  ]);
}

function узел(имя, атрибуты, класс) {
  const э = document.createElementNS(SVG, имя);
  for (const [к, з] of Object.entries(атрибуты)) э.setAttribute(к, з);
  if (класс) э.setAttribute("class", класс);
  return э;
}

function нарисовать_оверлей() {
  const данные = состояние.текущий;
  const svg = $("оверлей");
  svg.innerHTML = "";
  svg.classList.remove("нанесение");
  const масштаб = данные.canvas / ($("обёртка").clientWidth || данные.canvas);
  const толщина = 2 * масштаб;
  const радиус = 7 * масштаб;

  const bb = данные.product_bbox;
  svg.append(узел("rect", {
    x: bb[0], y: bb[1], width: bb[2] - bb[0], height: bb[3] - bb[1],
    "stroke-width": толщина,
  }, "силуэт"));

  for (const ф of состояние.фигуры) нарисовать_фигуру(svg, ф, толщина, радиус);

  const р = состояние.рамка;
  const точки = углы(р);
  svg.append(узел("polygon", {
    points: точки.map((т) => т.join(",")).join(" "),
    "stroke-width": толщина * 1.5, "data-роль": "тело",
  }, "рамка"));
  svg.append(узел("line", {
    x1: точки[0][0] + (точки[3][0] - точки[0][0]) / 2,
    y1: точки[0][1] + (точки[3][1] - точки[0][1]) / 2,
    x2: точки[1][0] + (точки[2][0] - точки[1][0]) / 2,
    y2: точки[1][1] + (точки[2][1] - точки[1][1]) / 2,
    "stroke-width": толщина,
  }, "рамка-ось"));

  точки.forEach((т, i) => svg.append(узел("circle", {
    cx: т[0], cy: т[1], r: радиус, "stroke-width": толщина, "data-угол": i,
  }, "ручка")));

  const a = (р.angle * Math.PI) / 180;
  const n = [Math.sin(a), -Math.cos(a)];
  const плечо = р.short / 2 + 34 * масштаб;
  const ручка = [р.cx + n[0] * плечо, р.cy + n[1] * плечо];
  svg.append(узел("line", {
    x1: р.cx + n[0] * (р.short / 2), y1: р.cy + n[1] * (р.short / 2),
    x2: ручка[0], y2: ручка[1], "stroke-width": толщина,
  }, "рамка-ось"));
  svg.append(узел("circle", {
    cx: ручка[0], cy: ручка[1], r: радиус, "stroke-width": толщина, "data-роль": "поворот",
  }, "ручка поворот"));

  if (состояние.шинка) {
    svg.append(узел("circle", {
      cx: состояние.шинка[0], cy: состояние.шинка[1], r: радиус * 1.05,
      "stroke-width": толщина, "data-роль": "шинка",
    }, "шинка-точка"));
  }
  обновить_поля();
}

/* Класс собирается из породы примитива и пометок фигуры: «разметка-текст
   правлена» — это подпись правленого размера. Порода нужна отдельно, потому что
   линию красит stroke, а подпись fill. */
function узел_части(часть, база, толщина, доп = "") {
  const класс = (имя) => (доп ? `${имя} ${доп}` : имя);
  if (часть.вид === "линия") {
    return узел("line", {
      x1: часть.x1, y1: часть.y1, x2: часть.x2, y2: часть.y2,
      "stroke-width": часть.род === "интервал" ? толщина * 1.6 : толщина,
    }, класс(база));
  }
  if (часть.вид === "точка") {
    return узел("circle", { cx: часть.x, cy: часть.y, r: часть.r }, класс(база + "-узел"));
  }
  if (часть.вид === "многоугольник") {
    return узел("polygon", { points: часть.точки }, класс(база + "-узел"));
  }
  const т = узел("text", {
    x: часть.x, y: часть.y,
    "font-size": часть.размер,
    "font-weight": часть.род === "подпись" ? 500 : 600,
    "text-anchor": "middle", "dominant-baseline": "central",
    transform: часть.поворот ? `rotate(${часть.поворот} ${часть.x} ${часть.y})` : "",
  }, класс(база + "-текст"));
  т.textContent = часть.текст;
  return т;
}

function нарисовать_фигуру(svg, ф, толщина, радиус) {
  const пометки = [состояние.правки[ф.key] ? "правлена" : "",
                   состояние.подсветка === ф.key ? "светится" : ""].join(" ").trim();
  for (const часть of части_фигуры(ф)) {
    const э = узел_части(часть, "разметка", толщина, пометки);
    э.dataset.ключ = ф.key;
    svg.append(э);
  }
  ручки_фигуры(svg, ф, толщина, радиус);
}

/* Ручки. Их роль читается из data-атрибутов при перетаскивании; здесь важно
   только, чтобы у каждого габарита нашлось за что взяться и чтобы взяться можно
   было пальцем, а не пикселем: невидимая широкая линия поверх размерной делает
   её саму хваткой. */
function ручки_фигуры(svg, ф, толщина, радиус) {
  const общее = { "stroke-width": толщина, "data-ключ": ф.key };
  if (ф.kind === "linear") {
    const [a, b] = [Math.min(ф.a, ф.b), Math.max(ф.a, ф.b)];
    const [x1, y1] = вдоль(ф.axis, a, ф.level);
    const [x2, y2] = вдоль(ф.axis, b, ф.level);
    svg.append(узел("line", {
      x1, y1, x2, y2,
      "stroke-width": радиус * 1.6, "data-роль": "уровень", "data-ключ": ф.key,
    }, "хват"));
    for (const [имя, з] of [["a", ф.a], ["b", ф.b]]) {
      const т = вдоль(ф.axis, з, ф.level);
      svg.append(узел("circle", {
        ...общее, cx: т[0], cy: т[1], r: радиус,
        "data-роль": "конец", "data-конец": имя,
      }, "ручка размерная"));
    }
  } else if (ф.kind === "inclined") {
    const [nx, ny] = ф.normal;
    const сдвиг = (т) => [т[0] + nx * ф.offset, т[1] + ny * ф.offset];
    const [начало, конец] = [сдвиг(ф.a), сдвиг(ф.b)];
    svg.append(узел("line", {
      x1: начало[0], y1: начало[1], x2: конец[0], y2: конец[1],
      "stroke-width": радиус * 1.6, "data-роль": "смещение", "data-ключ": ф.key,
    }, "хват"));
    for (const [имя, т] of [["a", начало], ["b", конец]]) {
      svg.append(узел("circle", {
        ...общее, cx: т[0], cy: т[1], r: радиус,
        "data-роль": "конец-точка", "data-конец": имя,
      }, "ручка размерная"));
    }
  } else if (ф.kind === "leader") {
    const полка = полка_выноски(ф, стиль_кадра()).конец;
    svg.append(узел("rect", {
      ...общее, x: ф.elbow[0] - радиус * 0.8, y: ф.elbow[1] - радиус * 0.8,
      width: радиус * 1.6, height: радиус * 1.6,
      transform: `rotate(45 ${ф.elbow[0]} ${ф.elbow[1]})`, "data-роль": "полка",
    }, "ручка полка"));
    svg.append(узел("rect", {
      ...общее, x: полка[0] - радиус * 0.7, y: полка[1] - радиус * 0.7,
      width: радиус * 1.4, height: радиус * 1.4, "data-роль": "разворот",
    }, "ручка разворот"));
    if (ф.span) {
      ф.span.forEach((т, i) => svg.append(узел("circle", {
        ...общее, cx: т[0], cy: т[1], r: радиус * 0.9,
        "data-роль": "интервал", "data-конец": i,
      }, "ручка интервал")));
    } else {
      const высота = ф.key === состояние.текущий.leader?.dim;
      if (высота) {
        const плечо = радиус * 2.1;
        svg.append(узел("path", {
          d: `M${ф.anchor[0] - плечо} ${ф.anchor[1]} L${ф.anchor[0] + плечо} ${ф.anchor[1]}`
             + ` M${ф.anchor[0]} ${ф.anchor[1] - плечо} L${ф.anchor[0]} ${ф.anchor[1] + плечо}`,
          "stroke-width": толщина,
        }, "якорь-крест"));
      }
      svg.append(узел("circle", {
        ...общее, cx: ф.anchor[0], cy: ф.anchor[1], r: радиус,
        "data-роль": "якорь",
      }, высота ? "якорь-точка" : "ручка стрелка"));
    }
  }
}

