# ---------------------------------------------------------------- холст

CANVAS = 2000                # сторона итогового PNG
REF_CANVAS = 1280            # эталоны SOKOLOV сняты на 1280 — от них берём пропорции стиля
PRODUCT_MAX_FRAC = 0.58      # какую долю холста занимает изделие по большей стороне
BG = (255, 255, 255)

def s(value: float) -> float:
    """Масштабирует величину, измеренную на эталоне 1280px, под текущий холст."""
    return value * CANVAS / REF_CANVAS

# ---------------------------------------------------------------- стиль

@dataclass(frozen=True)
class Style:
    line_color: tuple = (120, 120, 120)
    text_color: tuple = (0, 0, 0)
    line_width: int = field(default_factory=lambda: max(2, round(s(2))))
    dot_radius: float = field(default_factory=lambda: s(4.0))
    #: Интервал шинки — единственная линия разметки, лежащая на самом изделии.
    #: Общий светло-серый на полированном металле пропадает: яркость шинки на
    #: кадре 194–234, линия 120 — на превью такая нитка сливается в фон. Поэтому
    #: у интервала свой цвет, своя толщина и светлая подложка под ним.
    band_color: tuple = (55, 55, 55)
    band_width: int = field(default_factory=lambda: max(3, round(s(2.6))))
    halo_color: tuple = (255, 255, 255, 170)
    halo_grow: float = field(default_factory=lambda: s(3))
    band_tick: float = field(default_factory=lambda: s(13))     # половина засечки на кромке шинки
    tick_over: float = field(default_factory=lambda: s(26))     # вынос выносной линии за размерную
    ext_gap: float = field(default_factory=lambda: s(14))       # зазор между изделием и выносной линией
    ext_max: float = field(default_factory=lambda: s(120))      # запас длины выносной линии и длина засечки, когда до металла дальше
    offset_1: float = field(default_factory=lambda: s(78))      # первый «эшелон» размерных линий
    offset_step: float = field(default_factory=lambda: s(96))   # шаг между эшелонами
    text_gap: float = field(default_factory=lambda: s(16))      # зазор текст ↔ размерная линия
    label_size: float = field(default_factory=lambda: s(43))    # «17 мм»
    caption_size: float = field(default_factory=lambda: s(19))  # «Толщина шинки»
    line_break: float = field(default_factory=lambda: s(22))    # разрыв размерной линии вокруг текста
    leader_len: float = field(default_factory=lambda: s(170))   # длина полки выноски
    min_margin: float = field(default_factory=lambda: s(26))    # минимальный отступ от края холста

STYLE = Style()

