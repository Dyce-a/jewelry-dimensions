#: выноской, а габаритами идут длина и ширина. Держим это правило: так разметка
#: читается одинаково по всей выборке.
HEIGHT_ON_LEADER = True
VISIBLE_KEYS = ("length", "width")

#: Какие размеры шинки показывать интервалом прямо на металле: размерная линия
#: поперёк сечения шинки, засечки на обеих кромках, число на полке рядом.
#:
#: Интервалом показывается только ширина — единственный размер шинки, который кадр
#: действительно показывает: снизу и на боку кольцо повёрнуто к камере плоскостью
#: шинки, и её сечение читается по маске (промер по 106 позициям выборки, где ширина
#: и толщина различаются, совпал с таблицей: медиана 0,96).
#:
#: Толщина уходит на выноску со стрелкой — так же, как высота декоративного элемента.
#: На ракурсе «три четверти» её на кадре нет: камера видит лицевую грань шинки, стенка
#: за ней скрыта, и любой прямой разрез читает ширину (медиана того же промера к
#: табличной толщине — 1,95, то есть вдвое больше). Разделить сечение по яркости тоже
#: не выходит: блик на полированном металле гуляет, устойчивой границы между гранью и
#: торцом нет. Показывать толщину интервалом на металле — значит выдавать за неё чужой
#: размер, и на кадре она получалась неотличимой от ширины.
#:
#: Пустой кортеж возвращает оба размера на выноску.
BAND_SPANS = ("band_w",)

#: Ось осевого разреза шинки: 'v' — по вертикали, 'h' — по горизонтали.
